CREATE TABLE IF NOT EXISTS public.delivery_payment (
    order_id bigint PRIMARY KEY REFERENCES public.customer_order(order_id) ON DELETE RESTRICT,
    method text NOT NULL CHECK (method IN ('CASH', 'ONLINE')),
    online_order_paid numeric(12,2) NOT NULL DEFAULT 0 CHECK (online_order_paid >= 0),
    online_tip numeric(12,2) NOT NULL DEFAULT 0 CHECK (online_tip >= 0),
    cash_tip numeric(12,2) NOT NULL DEFAULT 0 CHECK (cash_tip >= 0),
    provider_reference text,
    verified_at TIMESTAMP WITH TIME ZONE,
    CHECK ((method = 'CASH' AND online_order_paid = 0 AND online_tip = 0)
        OR (method = 'ONLINE' AND cash_tip = 0 AND verified_at IS NOT NULL))
);

CREATE TABLE IF NOT EXISTS public.driver_settlement (
    settlement_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shift_id bigint NOT NULL UNIQUE REFERENCES public.driver_shift(shift_id),
    driver_id bigint NOT NULL REFERENCES public.driver_profile(driver_id),
    branch_id integer NOT NULL REFERENCES public.branch(branch_id),
    manager_id bigint REFERENCES public.customers(id),
    manager_username varchar(255) NOT NULL,
    order_sales numeric(12,2) NOT NULL,
    online_order_paid numeric(12,2) NOT NULL DEFAULT 0,
    online_tips numeric(12,2) NOT NULL DEFAULT 0,
    cash_tips numeric(12,2) NOT NULL DEFAULT 0,
    hourly_pay numeric(12,2) NOT NULL,
    delivery_pay numeric(12,2) NOT NULL,
    expected_cash_due numeric(12,2) NOT NULL,
    cash_handed_in numeric(12,2) NOT NULL DEFAULT 0 CHECK (cash_handed_in >= 0),
    cash_paid_out numeric(12,2) NOT NULL DEFAULT 0 CHECK (cash_paid_out >= 0),
    variance numeric(12,2) NOT NULL,
    variance_reason text,
    settled_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now()
);

