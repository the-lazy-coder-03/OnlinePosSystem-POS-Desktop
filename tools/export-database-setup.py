#!/usr/bin/env python3
"""Export fresh-database SQL from the application's authoritative migrations."""
import argparse
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
RESOURCES = ROOT / 'store-server/src/main/resources/db'
OUTPUT = ROOT / 'docs/database'


def clean(source):
    return re.sub(r'(?m)^[ \t]+$', '', source.rstrip())


def fresh_money_projection():
    schema = json.loads((RESOURCES.parent / 'catalogue-schema-v1.json').read_text())
    fields = [(table, column) for table, details in schema.items()
              for column in details.get('columns', {})
              if column in ('price', 'additional_price', 'bundle_price')]
    return ('\n-- BEGIN V4__exact_catalogue_money (fresh-empty-schema SQL projection of Java migration)\n'
            '-- Existing-value preflight remains in db.h2.V4__exact_catalogue_money; use Flyway for upgrades.\n'
            + ''.join(f'ALTER TABLE public.{table} ALTER COLUMN {column} DECIMAL(18,2);\n'
                      for table, column in fields)
            + '-- END V4__exact_catalogue_money\n')


def render(directory, engine, preamble):
    files = sorted(directory.glob('V*__*.sql'),
                   key=lambda path: int(re.match(r'V(\d+)__', path.name)[1]))
    header = (
        f'-- OnlinePOS complete {engine} fresh-database setup.\n'
        '-- Generated by tools/export-database-setup.py; edit migrations, then regenerate.\n'
        '-- Use an EMPTY, dedicated local database. This is not an upgrade script.\n'
        '-- Do not run this manually against an application-managed database.\n'
        '-- Includes migration seed/configuration rows; no customer or order exports.\n'
        '-- Does not create database users, credentials, or Flyway history.\n'
        '-- See docs/database/README.md before use.\n\n'
    )
    return header + preamble + ''.join(
        f'\n-- BEGIN {path.name}\n{clean(path.read_text())}\n-- END {path.name}\n'
        + (fresh_money_projection() if engine == 'H2' and path.name.startswith('V3__') else '')
        for path in files)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Fail if exports are outdated')
    args = parser.parse_args()
    outputs = {
        'postgresql-setup.sql': render(RESOURCES / 'migration', 'PostgreSQL', 'BEGIN;\n') + '\nCOMMIT;\n',
        'h2-setup.sql': render(RESOURCES / 'h2-migration', 'H2', 'CREATE SCHEMA dev_meta;\nSET SCHEMA dev_meta;\n'),
    }
    OUTPUT.mkdir(parents=True, exist_ok=True)
    for name, sql in outputs.items():
        path = OUTPUT / name
        if args.check:
            if not path.exists() or path.read_text() != sql:
                raise SystemExit(f'Outdated export: {path}')
            print(f'Current: {name}')
        else:
            path.write_text(sql)
            print(f'Written: {path}')


if __name__ == '__main__':
    main()
